// Run after replacing the PNG files in this folder:   node brand/embed-logos.mjs
// logo.png       = colours on transparent background (light backgrounds)
// logo-dark.png  = for dark backgrounds (sidebar, welcome page)
// logo-white.png = all white (login panel)
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const enc = f => 'data:image/png;base64,' + readFileSync(new URL(f, here)).toString('base64');
const out = "// AUTO-GENERATED by brand/embed-logos.mjs\n" +
  `export const LOGO = '${enc('logo.png')}';\n` +
  `export const LOGO_DARK = '${enc('logo-dark.png')}';\n` +
  `export const LOGO_WHITE = '${enc('logo-white.png')}';\n`;
writeFileSync(new URL('../src/app/core/brand.ts', here), out);
console.log('src/app/core/brand.ts updated');
